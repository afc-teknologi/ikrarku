import fs from 'node:fs'
const app=fs.readFileSync('src/App.tsx','utf8')
const css=fs.readFileSync('src/App.css','utf8')
const checks=[]; const check=(name,ok)=>checks.push([name,Boolean(ok)])
check('Zero-design preview has intentional empty state',app.includes('actual-preview-empty')&&app.includes('Blank design'))
check('Greetings has intentional empty state',app.includes('Belum ada ucapan. Jadilah yang pertama.'))
check('Feature width clamps to safe 20–100 range',app.includes('Math.max(20, Math.min(100, feature.objectWidth ?? 100))'))
check('Opening duration has minimum safety bound',app.includes('Math.max(150, coverEntry.feature.coverExitDuration ?? 700)'))
check('Opening duration UI has bounded 150–1800 range',app.includes('min="150" max="1800" step="50"'))
check('Cover background upload remains optional',app.includes('Optional · background image default None'))
check('Cover reference image removed from cover base CSS',!css.slice(css.indexOf('.invitation-cover-screen'),css.indexOf('.invitation-cover-screen')+520).includes('cover-reference.png'))
check('Reduced motion collapses cover transition',css.includes('@media (prefers-reduced-motion: reduce)')&&css.includes('coverV15Fade .12s linear'))
check('Mobile landing breakpoint exists',css.includes('@media(max-width:560px)'))
check('Multi-column cover collapses on small mobile',css.includes('.invitation-cover-grid.columns-4{grid-template-columns:1fr}'))
check('Sound right alignment maps to right edge',css.includes('.fixed-sound-disc.sound-pos-right{left:auto;right:22px}'))
check('Full-width feature alignment is represented by stretch',app.includes("objectAlign: 'stretch' as FeatureObjectAlign")&&app.includes("['stretch',AlignJustify]"))
check('Template preview handles missing sections',app.includes('visibleSections.length?visibleSections.map')&&app.includes('actual-preview-empty'))
check('Feature Library search handles no matches without crash',app.includes('widgetLibrary.filter(widget=>'))
check('Duplicate feature generates new ID',app.includes("copy.id = uid('feature')"))
const fail=checks.filter(([,ok])=>!ok)
for(const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`)
console.log(`\nEdge QA v0.15: ${checks.length-fail.length}/${checks.length} passed`)
if(fail.length)process.exit(1)
